// Generates fresh random passwords for the demo accounts and writes:
//   js/auth-config.js  — salted PBKDF2-SHA256 hashes only (safe to commit)
//   CREDENTIALS.md     — plaintext passwords (git-ignored, never commit)
// Usage: node tools/make-credentials.mjs   (re-running rotates both passwords)
import { randomBytes, randomInt, pbkdf2Sync } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ITERATIONS = 310000;
const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789!#%*+-=?@';
const makePassword = (len = 14) => {
  // guarantee at least one lower, upper, digit and symbol
  const sets = ['abcdefghijkmnopqrstuvwxyz', 'ABCDEFGHJKLMNPQRSTUVWXYZ', '23456789', '!#%*+-=?@'];
  for (;;) {
    let p = '';
    for (let i = 0; i < len; i++) p += ALPHABET[randomInt(ALPHABET.length)];
    if (sets.every((s) => [...p].some((c) => s.includes(c)))) return p;
  }
};

const accounts = [
  { username: 'admin', role: 'admin', displayName: 'Demo Admin' },
  { username: 'viewer', role: 'viewer', displayName: 'Demo Viewer' },
];
const plain = [];
const users = accounts.map((a) => {
  const password = makePassword();
  const salt = randomBytes(16);
  const hash = pbkdf2Sync(password, salt, ITERATIONS, 32, 'sha256');
  plain.push({ ...a, password });
  return { ...a, salt: salt.toString('base64'), hash: hash.toString('base64') };
});

const js = `/* Generated by tools/make-credentials.mjs — salted PBKDF2-SHA256 hashes only.
   Demo access gate for a static site: it is NOT real security (all code runs in the browser). */
'use strict';
window.RW_AUTH_CONFIG = Object.freeze({
  algorithm: 'PBKDF2',
  hash: 'SHA-256',
  iterations: ${ITERATIONS},
  keyLength: 32,
  sessionMinutes: 60,
  users: Object.freeze(${JSON.stringify(users, null, 2).replace(/\n/g, '\n  ')}),
});
`;
writeFileSync(join(root, 'js', 'auth-config.js'), js);

const md = `# RouteWise — demo credentials

> Git-ignored. Do not commit or share publicly. Regenerate with \`node tools/make-credentials.mjs\`.

| Username | Password | Role |
|---|---|---|
${plain.map((p) => `| \`${p.username}\` | \`${p.password}\` | ${p.role} |`).join('\n')}

- **admin** — can create/edit journey plans, weekly templates and KPI tasks (saved in this browser's localStorage).
- **viewer** — read-only.
`;
writeFileSync(join(root, 'CREDENTIALS.md'), md);
console.log('Wrote js/auth-config.js and CREDENTIALS.md');
